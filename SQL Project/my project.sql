    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS MarginPct,
    CASE
        WHEN SUM(Profit)/NULLIF(SUM(NetSales),0) >= 0.30 THEN 'Excellent'
        WHEN SUM(Profit)/NULLIF(SUM(NetSales),0) >= 0.20 THEN 'Good'
        WHEN SUM(Profit)/NULLIF(SUM(NetSales),0) >= 0.10 THEN 'Acceptable'
        ELSE 'Needs Review'
    END AS PerformanceStatus
FROM dbo.Sales
GROUP BY Category
ORDER BY Revenue DESC;
GO

