-- Data quality checks
SELECT COUNT(*) AS TotalRows FROM dbo.Sales;
SELECT COUNT(DISTINCT CustomerID) AS UniqueCustomers, COUNT(DISTINCT OrderID) AS UniqueOrders FROM dbo.Sales;
SELECT * FROM dbo.Sales WHERE Quantity <= 0 OR UnitPrice < 0 OR CostPrice < 0 OR DiscountPct NOT BETWEEN 0 AND 1;

-- 1) Executive KPIs
SELECT
    SUM(NetSales) AS TotalRevenue,
    SUM(Profit) AS TotalProfit,
    SUM(Quantity) AS UnitsSold,
    COUNT(DISTINCT OrderID) AS TotalOrders,
    COUNT(DISTINCT CustomerID) AS UniqueCustomers,
    CAST(SUM(NetSales) / NULLIF(COUNT(DISTINCT OrderID),0) AS DECIMAL(18,2)) AS AverageOrderValue,
    CAST(SUM(Profit) / NULLIF(SUM(NetSales),0) * 100 AS DECIMAL(10,2)) AS ProfitMarginPct
FROM dbo.Sales;

-- 2) Monthly revenue/profit trend
SELECT
    YEAR(OrderDate) AS SalesYear,
    MONTH(OrderDate) AS SalesMonth,
    SUM(NetSales) AS Revenue,
    SUM(Profit) AS Profit,
    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS ProfitMarginPct
FROM dbo.Sales
GROUP BY YEAR(OrderDate), MONTH(OrderDate)
ORDER BY SalesYear, SalesMonth;

-- 3) Category performance
SELECT
    Category,
    SUM(NetSales) AS Revenue,
    SUM(Profit) AS Profit,
    SUM(Quantity) AS UnitsSold,
    COUNT(DISTINCT OrderID) AS Orders,
    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS ProfitMarginPct,
    RANK() OVER (ORDER BY SUM(NetSales) DESC) AS RevenueRank
FROM dbo.Sales
GROUP BY Category
ORDER BY Revenue DESC;

-- 4) Top 10 products by revenue
SELECT TOP 10
    Product, Category,
    SUM(NetSales) AS Revenue,
    SUM(Profit) AS Profit,
    SUM(Quantity) AS UnitsSold,
    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS MarginPct
FROM dbo.Sales
GROUP BY Product, Category
ORDER BY Revenue DESC;

-- 5) Regional performance
SELECT
    Region, SUM(NetSales) AS Revenue, SUM(Profit) AS Profit,
    COUNT(DISTINCT OrderID) AS Orders,
    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS MarginPct
FROM dbo.Sales
GROUP BY Region
ORDER BY Revenue DESC;

-- 6) Sales channel analysis
SELECT
    SalesChannel, SUM(NetSales) AS Revenue, SUM(Profit) AS Profit,
    COUNT(DISTINCT OrderID) AS Orders,
    CAST(SUM(NetSales)/NULLIF(COUNT(DISTINCT OrderID),0) AS DECIMAL(18,2)) AS AOV
FROM dbo.Sales
GROUP BY SalesChannel
ORDER BY Revenue DESC;

-- 7) Customer value segmentation
WITH CustomerStats AS (
    SELECT CustomerID, SUM(NetSales) AS Revenue, SUM(Profit) AS Profit, COUNT(*) AS Orders
    FROM dbo.Sales GROUP BY CustomerID
)
SELECT CustomerID, Revenue, Profit, Orders,
    CASE
        WHEN Revenue >= 100000 THEN 'VIP'
        WHEN Revenue >= 50000 THEN 'High Value'
        WHEN Revenue >= 20000 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS CustomerSegment
FROM CustomerStats
ORDER BY Revenue DESC;

-- 8) Running monthly revenue
WITH Monthly AS (
    SELECT DATEFROMPARTS(YEAR(OrderDate), MONTH(OrderDate), 1) AS MonthStart, SUM(NetSales) AS Revenue
    FROM dbo.Sales GROUP BY DATEFROMPARTS(YEAR(OrderDate), MONTH(OrderDate), 1)
)
SELECT MonthStart, Revenue,
    SUM(Revenue) OVER (ORDER BY MonthStart ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RunningRevenue
FROM Monthly ORDER BY MonthStart;

-- 9) Month-over-month growth
WITH Monthly AS (
    SELECT DATEFROMPARTS(YEAR(OrderDate), MONTH(OrderDate), 1) AS MonthStart, SUM(NetSales) AS Revenue
    FROM dbo.Sales GROUP BY DATEFROMPARTS(YEAR(OrderDate), MONTH(OrderDate), 1)
), X AS (
    SELECT MonthStart, Revenue, LAG(Revenue) OVER (ORDER BY MonthStart) AS PreviousRevenue FROM Monthly
)
SELECT MonthStart, Revenue, PreviousRevenue,
    CAST((Revenue - PreviousRevenue)/NULLIF(PreviousRevenue,0)*100 AS DECIMAL(10,2)) AS MoMGrowthPct
FROM X ORDER BY MonthStart;

-- 10) Discount impact
SELECT
    DiscountPct * 100 AS DiscountPercent,
    COUNT(*) AS Orders,
    SUM(NetSales) AS Revenue,
    SUM(Profit) AS Profit,
    CAST(SUM(Profit)/NULLIF(SUM(NetSales),0)*100 AS DECIMAL(10,2)) AS MarginPct
FROM dbo.Sales
GROUP BY DiscountPct
ORDER BY DiscountPct;

